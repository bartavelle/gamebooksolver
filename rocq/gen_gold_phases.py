#!/usr/bin/env python3
"""Generates gold_phases.v: the chapters of Book 5 that can be played before and after the equipment is stored, as computed
by grow_n in gold_more.v. It doesn't have to be trusted, as gold_books.v checks the table on the book."""
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
PASSES = 60

SRC = f"""Set Printing Depth 1000000.
Require Import chapters rules gold_more.
Require book05.
Require Import Stdlib.Lists.List Stdlib.PArith.PArith.
Definition b := expand_evasions 5 book05.chapters.
Definition start := add_set (add_set (add_set (PM.empty bool, PM.empty bool) (Before, 1)) (Before, 0)) (After, 0).
Definition t := Eval vm_compute in grow_n {PASSES} b start.
Eval vm_compute in (chapters_ok (in_set t) b).
Eval vm_compute in (map (fun kv => Nat.pred (Pos.to_nat (fst kv))) (PM.elements (fst t))).
Eval vm_compute in (map (fun kv => Nat.pred (Pos.to_nat (fst kv))) (PM.elements (snd t))).
"""


def main():
    name = "gold_phases_scratch"
    path = os.path.join(HERE, name + ".v")
    with open(path, "w", encoding="utf-8") as f:
        f.write(SRC)
    try:
        out = subprocess.run(["rocq", "compile", "-w", "none", "-R", ".", "LoneWolfProofs", name + ".v"],
                             cwd=HERE, check=True, capture_output=True, text=True).stdout
    finally:
        for g in os.listdir(HERE):
            if g.startswith(name) or g.startswith("." + name):
                os.remove(os.path.join(HERE, g))
    if "..." in out or not out.lstrip().startswith("= true"):
        raise ValueError("the table is not complete, or not closed: " + out[:200])
    lists = [[int(x) for x in re.findall(r"\d+", part)] for part in re.split(r": list", out)[:2]]
    body = ["(* Generated by gen_gold_phases.py, and checked by gold_books.v. *)", "Require Import Stdlib.Lists.List.", "Import ListNotations.", ""]
    for n, l in zip(("before5", "after5"), lists):
        body.append(f"Definition {n} : list nat := [" + "; ".join(str(x) for x in l) + "].")
    with open(os.path.join(HERE, "proofs", "gold_phases.v"), "w", encoding="utf-8") as f:
        f.write("\n".join(body) + "\n")


if __name__ == "__main__":
    main()
