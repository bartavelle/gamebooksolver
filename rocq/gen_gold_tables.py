#!/usr/bin/env python3
"""Generates gold_tables.v: how much gold each chapter of the books can use, as computed by needs_from in gold_needs.v. This
takes minutes for each book, and doesn't have to be trusted, as gold_books.v checks the tables on the books."""
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
WIN_NEEDS = {1: 255, 2: 0, 3: 0, 5: 0}  # the gold only crosses from book 1


def table(b):
    name = f"gold_table_scratch{b}"
    src = f"""Set Printing Depth 1000000.
Require Import chapters rules gold_needs.
Require book0{b}.
Require Import Stdlib.Lists.List.
Definition b := expand_evasions {b} book0{b}.chapters.
Definition t := Eval vm_compute in needs_from b {WIN_NEEDS[b]} 60 (PM.empty _).
Eval vm_compute in (needs_ok b {WIN_NEEDS[b]} t).
Eval vm_compute in (map (fun cd => (fst cd, need_of t (fst cd))) b).
"""
    path = os.path.join(HERE, name + ".v")
    with open(path, "w", encoding="utf-8") as f:
        f.write(src)
    try:
        out = subprocess.run(["rocq", "compile", "-w", "none", "-R", ".", "LoneWolfProofs", name + ".v"],
                             cwd=HERE, check=True, capture_output=True, text=True).stdout
    finally:
        for g in os.listdir(HERE):
            if g.startswith(name) or g.startswith("." + name):
                os.remove(os.path.join(HERE, g))
    return out


def parse(out):
    if "..." in out or not out.lstrip().startswith("= true"):
        raise ValueError("the table is not complete, or not a fixpoint: " + out[:80])
    rest = out.split("= true", 1)[1]
    return [(int(a), int(c)) for a, c in re.findall(r"\(\s*(\d+)\s*,\s*(\d+)\s*\)", rest)]


def main():
    lines = ["(* Generated by gen_gold_tables.py, and checked by gold_books.v. Chapters that are not listed need no gold. *)",
             "Require Import Stdlib.Lists.List.", "Import ListNotations.", ""]
    for b in sorted(WIN_NEEDS):
        entries = [e for e in parse(table(b)) if e[1] != 0]
        body = "; ".join(f"({c},{n})" for c, n in entries)
        lines.append(f"Definition needs{b} : list (nat * nat) := [{body}].")
    with open(os.path.join(HERE, "proofs", "gold_tables.v"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
